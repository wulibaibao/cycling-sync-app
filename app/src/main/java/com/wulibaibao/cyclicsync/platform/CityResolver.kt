    /** 按坐标反查城市名。匹配不到返回 null。 */
    fun resolve(lat: Double, lon: Double): String? {
        if (lat.isNaN() || lon.isNaN() || lat == 0.0 && lon == 0.0) return null
        var best = -1
        var bestD = Double.MAX_VALUE
        for (i in NAMES.indices) {
            val d = distanceMeters(lat, lon, COORDS[i * 2].toDouble(), COORDS[i * 2 + 1].toDouble())
            if (d < bestD) {
                bestD = d
                best = i
            }
        }
        return if (best >= 0 && bestD <= MAX_DISTANCE_M) NAMES[best] else null
    }

    /**
     * 兜底：用 FIT 里的原始坐标（GCJ-02）反查。
     * GCJ-02 与 WGS-84 差 ~500m，城市匹配半径 35km，所以误差可接受。
     */
    fun resolveFromRaw(fit: ByteArray): String? {
        val pt = FitCoordRewriter.firstRawPoint(fit) ?: return null
        return resolve(pt[0], pt[1])
    }

    /** 两点球面距离（米）。 */
    fun distanceMeters(lat1: Double, lon1: Double, lat2: Double, lon2: Double): Double {
        val r = 6371000.0
        val p1 = Math.toRadians(lat1)
        val p2 = Math.toRadians(lat2)
        val dp = Math.toRadians(lat2 - lat1)
        val dl = Math.toRadians(lon2 - lon1)
        val a = sin(dp / 2) * sin(dp / 2) + cos(p1) * cos(p2) * sin(dl / 2) * sin(dl / 2)
        return 2 * r * asin(sqrt(a))
    }
